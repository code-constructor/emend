import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { splitMigrationStatements } from "./src/db/migration-sql.ts";

const root = new URL("./drizzle/", import.meta.url);
const journal = JSON.parse(await readFile(new URL("meta/_journal.json", root), "utf8")) as {
  entries: { tag: string; when: number }[];
};
const migrations = await Promise.all(
  journal.entries.map(async ({ tag, when }) => {
    const source = await readFile(new URL(`${tag}.sql`, root), "utf8");
    return {
      tag,
      when,
      hash: createHash("sha256").update(source).digest("hex"),
      statements: splitMigrationStatements(source),
    };
  }),
);
await writeFile(
  new URL("./src/db/migrations.gen.ts", import.meta.url),
  `// Generated by embed-migrations.ts; do not edit.\nexport const MIGRATIONS: readonly { tag: string; when: number; hash: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
